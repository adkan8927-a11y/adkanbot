def classify_stock_to_sector(name: str, code: str) -> str:
    """
    종목명 기반으로 가장 적합한 핵심 섹터 분류
    - 1차: 딕셔너리 상단 우선순위 키워드 매칭
    - 2차: 매칭 실패 시 종목명 자체가 키워드인지 재검색
    - 최종: 미분류 → '기타 주도주'
    """
    for sector_name, keywords in SECTOR_MAPPER.items():
        for kw in keywords:
            if kw in name:
                return sector_name
    return "기타 주도주"


def get_top_sectors(screened_stocks: list, top_n: int = 5) -> list:
    """
    포착 종목 리스트를 섹터별로 그룹화하고 상위 N대 핵심 섹터 추출.

    개선 포인트:
    - 5개 미달 시 고정 섹터로 채우는 로직 완전 제거
    - 실제 포착된 섹터만 반환 (최대 top_n개)

    Args:
        screened_stocks (list): [{'name': ..., 'code': ..., 'amount_100m': ...}]
        top_n (int): 반환할 최대 섹터 수 (기본 5)

    Returns:
        list: 핵심 섹터 정보 리스트 (실제 포착 수만큼, 최대 top_n개)
    """
    sector_groups = {}

    for stock in screened_stocks:
        name = stock["name"]
        code = stock["code"]
        sec = classify_stock_to_sector(name, code)

        if sec not in sector_groups:
            sector_groups[sec] = {
                "sector_name": sec,
                "stocks": [],
                "total_amount": 0.0,
                "count": 0
            }
        sector_groups[sec]["stocks"].append(name)
        sector_groups[sec]["total_amount"] += stock.get("amount_100m", 0.0)
        sector_groups[sec]["count"] += 1

    # 종목 수 우선, 거래대금 차순 정렬
    sorted_sectors = sorted(
        sector_groups.values(),
        key=lambda x: (x["count"], x["total_amount"]),
        reverse=True
    )

    # '기타 주도주' 버킷이 1위를 차지하면 순위에서 후순위로 밀기
    others = [s for s in sorted_sectors if s["sector_name"] == "기타 주도주"]
    main = [s for s in sorted_sectors if s["sector_name"] != "기타 주도주"]
    sorted_sectors = main + others

    # 실제 포착 섹터만 반환 (고정 채움 없음)
    return sorted_sectors[:top_n]


# 하위 호환성: 기존 코드에서 get_top5_sectors() 를 호출하는 경우 대비
def get_top5_sectors(screened_stocks: list) -> list:
    return get_top_sectors(screened_stocks, top_n=5)
